"""Temporal alignment for spiking continual learning.

Why this exists
---------------
A spiking network does not emit a single logit vector: it emits a *trajectory*
``h_1 .. h_T``. When a new task is learned, the trajectory for old classes does not
only shrink or grow — it **shifts in time**: the class evidence that used to appear
at step 2 now appears at step 3. A per-timestep KL (``h_t^student`` vs ``h_t^teacher``)
cannot express that, so it penalises a harmless re-timing exactly as much as a
genuine change of content.

Soft-DTW (Cuturi & Blondel, 2017) fixes this: it computes the cheapest *alignment*
between two sequences and is differentiable, so the student is free to put its
evidence slightly earlier or later as long as the overall trajectory matches. This is
the mechanism STAER (2026) uses for continual spiking networks; here the "other
scale" trajectory is generated by re-encoding the *same* stored image at a different
number of time steps, which is exactly the compression/dilation the brain is
hypothesised to use during replay.

Both trajectories are logits of shape ``(B, T, K)``; the returned distance is
``(B,)``.
"""

from __future__ import annotations

from typing import Tuple

import torch
import torch.nn.functional as F


def softmin3(a: torch.Tensor, b: torch.Tensor, c: torch.Tensor,
             gamma: float) -> torch.Tensor:
    """``-gamma * log(exp(-a/g) + exp(-b/g) + exp(-c/g))`` computed stably."""
    stacked = torch.stack([a, b, c], dim=0) / gamma
    return -gamma * torch.logsumexp(-stacked, dim=0)


def soft_dtw(x: torch.Tensor, y: torch.Tensor, gamma: float = 1.0,
             normalize: bool = True) -> torch.Tensor:
    """Differentiable DTW between batched sequences.

    Parameters
    ----------
    x : (B, T, K)
    y : (B, S, K)
    gamma : softness; ``gamma -> 0`` recovers hard DTW, larger values average over
        more alignments.
    normalize : divide by ``T + S`` so sequences of different length are comparable.

    Returns
    -------
    (B,) soft-DTW distances.
    """
    if x.dim() != 3 or y.dim() != 3:
        raise ValueError(f"expected (B,T,K) inputs, got {tuple(x.shape)} and {tuple(y.shape)}")
    if x.shape[0] != y.shape[0] or x.shape[2] != y.shape[2]:
        raise ValueError("batch size and feature dim must match")
    B, T, K = x.shape
    S = y.shape[1]
    gamma = max(float(gamma), 1e-3)

    # pairwise cost d[i, j] = ||x_i - y_j||^2   -> (T, S, B)
    d = (x.unsqueeze(2) - y.unsqueeze(1)).pow(2).sum(-1).permute(1, 2, 0)

    inf = torch.full((B,), float("inf"), device=x.device, dtype=x.dtype)
    R = x.new_full((T, S, B), float("inf"))
    R[0, 0] = d[0, 0]
    for i in range(1, T):                       # first column: only vertical moves
        R[i, 0] = d[i, 0] + R[i - 1, 0]
    for j in range(1, S):                       # first row: only horizontal moves
        R[0, j] = d[0, j] + R[0, j - 1]
    for i in range(1, T):
        for j in range(1, S):
            prev = softmin3(R[i - 1, j], R[i - 1, j - 1], R[i, j - 1], gamma)
            R[i, j] = d[i, j] + torch.where(torch.isinf(prev), inf, prev)

    out = R[T - 1, S - 1]
    if normalize:
        out = out / float(T + S)
    return out


def temporal_alignment_loss(student: torch.Tensor, teacher: torch.Tensor,
                            gamma: float = 1.0) -> torch.Tensor:
    """Scalar loss aligning the student trajectory to a (detached) teacher one.

    The raw soft-DTW can be slightly negative when the two sequences are almost
    identical (the soft-min at the start of the DP dips below the hard min). That
    would turn "make the logits tiny" into a way of reducing the loss, so the cost
    of aligning the teacher with *itself* is subtracted (a constant with respect to
    the student) and the result is clamped at zero.
    """
    teacher = teacher.detach()
    raw = soft_dtw(student, teacher, gamma=gamma)
    floor = soft_dtw(teacher, teacher, gamma=gamma).detach()
    return (raw - floor).clamp_min(0.0).mean()


def resample_logits(logits: torch.Tensor, target_len: int) -> torch.Tensor:
    """Linear resampling of a (B, T, K) trajectory to ``target_len`` steps.

    Used when the teacher trajectory length differs from the student's but a plain
    alignment is wanted without re-running the network.
    """
    B, T, K = logits.shape
    if T == target_len:
        return logits
    flat = logits.permute(0, 2, 1)                       # (B, K, T)
    out = F.interpolate(flat, size=target_len, mode="linear", align_corners=True)
    return out.permute(0, 2, 1)
